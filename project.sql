-- =====================================================================
-- TA-andmebaas – kinoprojekti planeeritud andmebaasi struktuur
-- Andmebaas: PostgreSQL 16
--
-- See fail on PLANEERIMISDOKUMENT: see kirjeldab sama skeemi, mille
-- Django ORM migratsioonidega (backend/cinema/migrations) tegelikult loob.
-- Päris andmebaasis tabeleid selle failiga EI looda – skeemi omanik on
-- Django (`python manage.py migrate`). Faili saab eraldi testandmebaasis
-- käivitada, et kontrollida süntaksit ja võrrelda struktuuri.
--
-- Erinevused ORM-i loodud skeemiga (sisuliselt samaväärsed):
--   * Django paneb indeksitele ja UNIQUE-piirangutele räsiga nimed
--     (nt user_email_54dc62b2_uniq); siin on loetavad nimed.
--   * Django võõrvõtmed on DEFERRABLE INITIALLY DEFERRED ja ON DELETE
--     käitumist (CASCADE/PROTECT) täidab Django ise. Siin on sama
--     käitumine kirjas otse ON DELETE reeglina.
--   * PositiveSmallIntegerField lisab veergudele automaatse CHECK (>= 0).
--   * Vaikeväärtused (DEFAULT '2D', false, 'ootel', now()) on siin
--     kirjas andmebaasi tasemel. Django paneb need Pythonis enne INSERT-i,
--     nii et ORM-i skeemis on need veerud ilma DEFAULT-ita.
-- =====================================================================

-- btree_gist on vajalik seansside kattuvuse keelu jaoks (EXCLUDE USING gist).
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ---------------------------------------------------------------------
-- Kasutajad
-- ---------------------------------------------------------------------
CREATE TABLE "user" (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "user"        varchar(255)  NOT NULL UNIQUE,          -- kasutajanimi
    first_name    varchar(1024) NOT NULL,
    last_name     varchar(1024) NOT NULL,
    phone_number  varchar(30)   NOT NULL,                 -- nt +372 5123456
    email         varchar(1024) NOT NULL UNIQUE,
    date_of_birth date,
    password_hash text          NOT NULL                  -- ainult räsi, mitte parool
);

-- ---------------------------------------------------------------------
-- Kinod, saalid ja istekohad (1:N:N)
-- ---------------------------------------------------------------------
CREATE TABLE kino (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kino_nimi        varchar(255) NOT NULL,
    "tänava_aadress" varchar(255) NOT NULL,
    linn             varchar(255) NOT NULL,
    postiindeks      varchar(32)  NOT NULL,
    riik             varchar(255) NOT NULL,
    CONSTRAINT unique_cinema_in_city UNIQUE (kino_nimi, linn)
);

CREATE TABLE kinosaalid (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kino_id        bigint      NOT NULL REFERENCES kino (id) ON DELETE RESTRICT,
    name           varchar(50) NOT NULL,
    "ekraani_tüüp" varchar(20) NOT NULL DEFAULT '2D',     -- 2D | 3D | IMAX
    mahutavus      smallint    NOT NULL,
    CONSTRAINT unique_hall_name_in_cinema UNIQUE (kino_id, name),
    CONSTRAINT hall_capacity_positive CHECK (mahutavus > 0)
);
CREATE INDEX kinosaalid_kino_id_idx ON kinosaalid (kino_id);

CREATE TABLE istekohad (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kinosaal_id bigint     NOT NULL REFERENCES kinosaalid (id) ON DELETE CASCADE,
    rida        varchar(3) NOT NULL,
    istekoht    smallint   NOT NULL CHECK (istekoht >= 0),
    CONSTRAINT unique_seat_in_hall UNIQUE (kinosaal_id, rida, istekoht)
);
CREATE INDEX istekohad_kinosaal_id_idx ON istekohad (kinosaal_id);

-- ---------------------------------------------------------------------
-- Filmid ja žanrid (M:N vahetabeli filmid_zanrid kaudu)
-- ---------------------------------------------------------------------
CREATE TABLE filmid (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pealkiri            varchar(255) NOT NULL,
    kirjeldus           text,
    filmi_pikkus        smallint     NOT NULL,             -- minutites
    "väljalaskekuupäev" date,
    vanusepiirang       varchar(10),                       -- PERE, MS-6, MS-12, K-12, K-14, K-16
    keel                varchar(50),
    plakati_url         varchar(500),
    treileri_url        varchar(500),
    "väikeväärtus"      boolean      NOT NULL DEFAULT false, -- Django väli is_featured (esiletõstetud)
    CONSTRAINT movie_duration_positive CHECK (filmi_pikkus > 0)
);

CREATE TABLE "žanrid" (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nimi varchar(50) NOT NULL UNIQUE
);

CREATE TABLE filmid_zanrid (
    id         bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filmi_id   integer NOT NULL REFERENCES filmid (id) ON DELETE CASCADE,
    "žanri_id" integer NOT NULL REFERENCES "žanrid" (id) ON DELETE CASCADE,
    CONSTRAINT unique_movie_genre UNIQUE (filmi_id, "žanri_id")
);
CREATE INDEX filmid_zanrid_filmi_id_idx ON filmid_zanrid (filmi_id);
CREATE INDEX filmid_zanrid_zanri_id_idx ON filmid_zanrid ("žanri_id");

-- ---------------------------------------------------------------------
-- Seansid: film + saal + aeg
-- ---------------------------------------------------------------------
CREATE TABLE seansid (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filmi_id   integer       NOT NULL REFERENCES filmid (id) ON DELETE CASCADE,
    saali_id   bigint        NOT NULL REFERENCES kinosaalid (id) ON DELETE CASCADE,
    algus_aeg  timestamptz   NOT NULL,
    lopu_aeg   timestamptz   NOT NULL,
    keel       varchar(50),
    subtiitrid varchar(50),
    alghind    numeric(8, 2) NOT NULL,
    CONSTRAINT screening_end_after_start CHECK (lopu_aeg > algus_aeg),
    CONSTRAINT screening_price_not_negative CHECK (alghind >= 0),
    -- Samas saalis ei tohi kaks seanssi ajaliselt kattuda.
    CONSTRAINT screening_no_overlap_in_hall
        EXCLUDE USING gist (saali_id WITH =, tstzrange(algus_aeg, lopu_aeg) WITH &&)
);
CREATE INDEX seansid_filmi_id_idx ON seansid (filmi_id);
CREATE INDEX seansid_saali_id_idx ON seansid (saali_id);
CREATE INDEX screening_start_idx ON seansid (algus_aeg);

-- ---------------------------------------------------------------------
-- Broneeringud, piletid (broneeritud kohad) ja maksed
-- ---------------------------------------------------------------------
CREATE TABLE broneeringud (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kasutaja_id bigint        NOT NULL REFERENCES "user" (id) ON DELETE CASCADE,
    seansi_id   integer       NOT NULL REFERENCES seansid (id) ON DELETE CASCADE,
    staatus     varchar(20)   NOT NULL DEFAULT 'ootel',  -- ootel | kinnitatud | tühistatud
    kogusumma   numeric(8, 2) NOT NULL,
    loodud      timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT booking_total_not_negative CHECK (kogusumma >= 0)
);
CREATE INDEX broneeringud_kasutaja_id_idx ON broneeringud (kasutaja_id);
CREATE INDEX broneeringud_seansi_id_idx ON broneeringud (seansi_id);

-- Üks rida = üks pilet ehk üks istekoht ühel seansil.
-- seansi_id kordab broneeringu seanssi, et UNIQUE (seansi_id, istekoha_id)
-- saaks keelata sama koha topeltmüügi. Reeglid "pileti seanss = broneeringu
-- seanss" ja "istekoht on seansi saalis" hõlmavad mitut tabelit; neid
-- kontrollivad BookedSeat.clean(), testid ja scripts/kontroll.sql.
CREATE TABLE broneeritud_kohad (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    broneeringu_id integer       NOT NULL REFERENCES broneeringud (id) ON DELETE CASCADE,
    seansi_id      integer       NOT NULL REFERENCES seansid (id) ON DELETE CASCADE,
    istekoha_id    integer       NOT NULL REFERENCES istekohad (id) ON DELETE CASCADE,
    hind           numeric(8, 2) NOT NULL,
    CONSTRAINT unique_booked_seat_per_screening UNIQUE (seansi_id, istekoha_id),
    CONSTRAINT booked_seat_price_not_negative CHECK (hind >= 0)
);
CREATE INDEX broneeritud_kohad_broneeringu_id_idx ON broneeritud_kohad (broneeringu_id);
CREATE INDEX broneeritud_kohad_istekoha_id_idx ON broneeritud_kohad (istekoha_id);

-- Ühel broneeringul võib olla mitu makset (nt ebaõnnestunud katse + edukas).
CREATE TABLE maksed (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    broneeringu_id integer       NOT NULL REFERENCES broneeringud (id) ON DELETE CASCADE,
    summa          numeric(8, 2) NOT NULL,
    makseviis      varchar(30)   NOT NULL,               -- kaart | pangalink | mobiilimakse
    staatus        varchar(20)   NOT NULL,               -- ootel | edukas | ebaõnnestunud | tagastatud
    makse_viide    varchar(255) UNIQUE,
    makstud        timestamptz,
    CONSTRAINT payment_amount_not_negative CHECK (summa >= 0)
);
CREATE INDEX maksed_broneeringu_id_idx ON maksed (broneeringu_id);

-- ---------------------------------------------------------------------
-- Arvustused: üks kasutaja saab filmi hinnata ühe korra
-- ---------------------------------------------------------------------
CREATE TABLE arvustused (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kasutaja_id bigint      NOT NULL REFERENCES "user" (id) ON DELETE CASCADE,
    filmi_id    integer     NOT NULL REFERENCES filmid (id) ON DELETE CASCADE,
    hinnang     smallint    NOT NULL,
    kommentaar  text,
    loodud      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT unique_review_per_user_movie UNIQUE (kasutaja_id, filmi_id),
    CONSTRAINT review_rating_1_to_5 CHECK (hinnang BETWEEN 1 AND 5)
);
CREATE INDEX arvustused_filmi_id_idx ON arvustused (filmi_id);
